import { expect, test, type Page } from '@playwright/test'

async function send(page: Page, query: string) {
  await page.getByRole('textbox', { name: '向 Lumi 提问' }).fill(query)
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
}
function latestReply(page: Page) {
  return page.getByRole('log', { name: '与 Lumi 的对话' }).locator(':scope > article').last()
}
async function finished(page: Page) {
  await expect(latestReply(page).getByRole('button', { name: '复制回复', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '停止生成', exact: true })).toHaveCount(0)
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function primaryNav(page: Page, mobile: boolean) {
  if (!mobile) return page.getByRole('navigation', { name: '主导航' })
  const quick = page.getByRole('navigation', { name: '快捷导航' })
  if (await quick.isVisible()) return quick
  await page.getByRole('button', { name: '打开菜单' }).click()
  return page.getByRole('dialog', { name: '菜单', exact: true }).getByRole('navigation', { name: '主导航' })
}
async function goHome(page: Page, mobile: boolean) {
  await page.getByRole('link', { name: mobile ? '回到首页' : 'Lumi 生活首页', exact: true }).click()
  await expect(page.getByRole('heading', { name: '今天', level: 1, exact: true })).toBeVisible()
}

async function goSaved(page: Page, mobile: boolean) {
  await (await primaryNav(page, mobile)).getByRole('link', { name: /^清单/ }).click()
  await expect(page.getByRole('heading', { name: '清单', level: 1, exact: true })).toBeVisible()
}
async function goChat(page: Page, mobile: boolean) {
  await (await primaryNav(page, mobile)).getByRole('link', { name: '对话', exact: true }).click()
}
async function openSettings(page: Page, mobile: boolean) {
  if (mobile) {
    await page.getByRole('button', { name: '打开菜单' }).click()
    await page.getByRole('dialog', { name: '菜单', exact: true }).getByRole('button', { name: '设置', exact: true }).click()
  } else await page.getByRole('button', { name: '偏好与演示设置' }).click()
}

test('brand shortcut returns home with keyboard and preserves the new-chat draft and network mode', async ({ page }, info) => {
  const mobile = info.project.name === 'mobile'
  await page.goto('/chat?mock_latency=slow')
  const input = page.getByRole('textbox', { name: '向 Lumi 提问' })
  await input.fill('稍后再问的问题')
  const home = page.getByRole('link', { name: mobile ? '回到首页' : 'Lumi 生活首页', exact: true })
  await expect(home).toBeVisible()
  await expect(home.locator('svg')).toHaveAttribute('aria-hidden', 'true')
  await home.focus()
  await expect(home).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL('/?mock_latency=slow')
  await expect(page.getByRole('heading', { name: '今天', level: 1, exact: true })).toBeVisible()
  await expect(input).toHaveValue('')
  if (mobile) await expect(home).toHaveAttribute('aria-current', 'page')
  await page.goBack()
  await expect(input).toHaveValue('稍后再问的问题')
  await page.reload()
  await expect(input).toHaveValue('稍后再问的问题')
  await expect(home).toHaveAttribute('href', '/?mock_latency=slow')
  const opened = page.context().waitForEvent('page')
  await home.click({ button: 'middle' })
  const homeTab = await opened
  await expect(homeTab).toHaveURL('/?mock_latency=slow')
  await expect(page).toHaveURL('/chat?mock_latency=slow')
  await expect(input).toHaveValue('稍后再问的问题')
  await homeTab.close()
  await page.goto('/chat/missing?mock_latency=slow')
  await expect(page.getByRole('heading', { name: '这段对话不在当前浏览器里' })).toBeVisible()
  await goHome(page, mobile)
  await expect(page).toHaveURL('/?mock_latency=slow')
  await page.goto('/saved')
  await goHome(page, mobile)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('lumi:v1')!).conversations.length)).toBe(0)
})

test('brand navigation stays usable with long chat titles across themes and breakpoints', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await send(page, '周末从武林广场去西湖再回杭州东站，怎么安排路线比较方便？')
  await finished(page)
  const path = new URL(page.url()).pathname
  const input = page.getByRole('textbox', { name: '向 Lumi 提问' })
  await input.fill('这段对话的未发送草稿')
  for (const width of [320, 390, 768, 1023, 1024, 1440]) {
    await page.setViewportSize({ width, height: width >= 1024 ? 900 : 844 })
    for (const theme of ['light', 'dark']) {
      await page.evaluate(value => { document.documentElement.dataset.theme = value }, theme)
      const home = page.getByRole('link', { name: width < 1024 ? '回到首页' : 'Lumi 生活首页', exact: true })
      await expect(home).toBeVisible()
      const box = await home.boundingBox()
      expect(box!.width).toBeGreaterThanOrEqual(44)
      expect(box!.height).toBeGreaterThanOrEqual(44)
      const headerFits = await page.locator('header').first().evaluate(header => {
        const left = header.querySelector('[class*="headerLeft"]')!.getBoundingClientRect()
        const right = header.querySelector('[class*="headerRight"]')!.getBoundingClientRect()
        const title = header.querySelector('[class*="headerTitle"]')!.getBoundingClientRect()
        return left.right <= right.left && title.width > 0 && right.right <= innerWidth
      })
      expect(headerFits).toBe(true)
      await noOverflow(page)
      await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
      if (width === (info.project.name === 'mobile' ? 390 : 1440)) {
        await page.screenshot({ animations: 'disabled', path: `docs/screenshots/${info.project.name}-brand-chat-${theme}.png` })
        if (width === 390) {
          await page.getByRole('button', { name: '打开菜单', exact: true }).click()
          await expect(page.getByRole('dialog', { name: '菜单', exact: true }).getByRole('heading', { name: '菜单', exact: true })).toBeVisible()
          await page.screenshot({ animations: 'disabled', path: `docs/screenshots/mobile-brand-menu-${theme}.png` })
          await page.keyboard.press('Escape')
          await expect(page.getByRole('dialog', { name: '菜单', exact: true })).toHaveCount(0)
        }
      }
      if (width === 320 && info.project.name === 'mobile') {
        await page.screenshot({ animations: 'disabled', path: `docs/screenshots/mobile-brand-narrow-${theme}.png` })
      }
      await home.click()
      await expect(page.getByRole('heading', { name: '今天', level: 1, exact: true })).toBeVisible()
      await page.getByRole('button', { name: '继续上次对话', exact: true }).click()
      await expect(page).toHaveURL(path)
      await expect(input).toHaveValue('这段对话的未发送草稿')
    }
  }
  expect(errors).toEqual([])
})

