function record(originalId, originalName, originalKind, cultivation, maxLv, tables, wuqi, resources = null) {
  const learning = {};
  for (const [i, key] of ['level', 'sp', 'gold'].entries()) {
    const values = tables[i];
    if (!Array.isArray(values) || values.length !== maxLv || values.some((n) => !Number.isFinite(n) || n < 0)) {
      throw new Error(`Non-numeric source learning table: ${originalName}/${key}`);
    }
    learning[key] = Object.freeze([...values]);
  }
  if (typeof wuqi !== 'string' || !wuqi.trim()) throw new Error(`Missing source weapon restriction: ${originalName}`);
  if (resources?.mp) Object.freeze(resources.mp);
  if (resources) Object.freeze(resources);
  return Object.freeze({ originalId, originalName, originalKind, variant: 'normal', xianmo: '3', cultivation, maxLv,
    wuqi, weapons: normalizeSkillWeapons(wuqi), resources, learning: Object.freeze(learning) });
}

