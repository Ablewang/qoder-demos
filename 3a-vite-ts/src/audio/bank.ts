const isGenerator = (i: any) => i && typeof i.next == "function";
function resolveSound(i: any, e: any, t: number) {
  let n = Array.isArray(e) ? e : [e];
  if (!i.loop) {
    for (let r of n) fadeEdges(r, t, i.ir ? 0 : 3e-4, i.ir ? 0.05 : 0.012);
  }
  let s = 0;
  for (let r of n) s = Math.max(s, peakOf(r));
  let o = s > 0 ? i.peak / s : 1;
  for (let r of n) gain(r, o);
  return {
    sr: t,
    ch: n,
    loop: !!i.loop,
  };
}
export function renderSound(
  i: string | number,
  e: any = 0,
  t: number | undefined,
) {
  let n = SOUND_BANK[i];
  if (!n) {
    return null;
  }
  let s = t || n.sr,
    o = e % n.n,
    r = n.gen(s, audioRng(hashStr(i) + o * 7919), o);
  if (isGenerator(r)) {
    let a: any;
    do a = r.next();
    while (!a.done);
    r = a.value;
  }
  return resolveSound(n, r, s);
}
export function renderSoundAsync(i: string, e = 0, t: number | undefined) {
  let n = SOUND_BANK[i];
  if (!n) {
    return null;
  }
  let s = t || n.sr,
    o = e % n.n,
    r = n.gen(s, audioRng(hashStr(i) + o * 7919), o),
    a: any = null;
  return {
    step() {
      if (a) {
        return a;
      }
      if (isGenerator(r)) {
        let l = r.next();
        if (!l.done) {
          return null;
        }
        r = l.value;
      }
      return (a = resolveSound(n, r, s));
    },
  };
}
